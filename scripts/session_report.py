#!/usr/bin/env python
"""Writes reports/session_<N>.md after a GPU session (EXPERIMENT_PLAN section 12).

    python scripts/session_report.py <N> [--seeds 0]

Runs done and minutes per run come from runs/logs/session_<N>.log (the queue's own log) and each run's
train_summary.json; the results tables come from scripts/aggregate.py e1 (written to reports/e1_interim.*
when --seeds is given); "next" is the first units of experiments/priority.txt that are not done yet.
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from session_queue import parse_plan, unit_done  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("n", type=int)
ap.add_argument("--seeds", default=None, help="comma list of seed sets separated by ';', e.g. '0;0,1'")
ap.add_argument("--plan", default="experiments/priority.txt")
a = ap.parse_args()
log = Path(f"runs/logs/session_{a.n}.log").read_text().splitlines()
L = [f"# GPU session {a.n}", "", "Generated by `scripts/session_report.py`. Validation-only numbers are marked; "
     "test numbers come from `scripts/aggregate.py e1` (paired subject bootstrap, 95% intervals). All shifts are "
     "within-database (Sleep-EDF); ST is development-grade.", ""]
head = next((l for l in log if "deadline" in l), "")
L += ["## Session", "", f"- Queue start: `{head}`", f"- Queue end: `{log[-1] if log else ''}`", ""]
L += ["## Runs done", "", "| run | train min | best val MF1 (validation) | best epoch | GPU peak MB |",
      "| --- | ---: | ---: | ---: | ---: |"]
for l in log:
    m = re.search(r"train (\S+): ok \(([\d.]+) min\)", l)
    if m:
        s = json.loads(Path(f"runs/{m.group(1)}/train_summary.json").read_text())
        L.append(f"| {m.group(1)} | {float(m.group(2)):.1f} | {s['best_val_mf1']:.4f} | {s['best_epoch']} | {s.get('gpu_peak_mb')} |")
L += ["", "Evaluations, interruptions and roll-overs:", ""]
L += [f"- `{l}`" for l in log if re.search(r"eval .*-> |KILLED|FAILED|does not fit|moved|retrying|check ", l)]
gates = sorted(Path("runs/gates").glob("val_gate_*.json")) if Path("runs/gates").exists() else []
if gates:
    L += ["", "## Validation gate (validation people only)", ""]
    for g in gates:
        d = json.loads(g.read_text())
        L.append(f"- {d['arm']} vs {d['ref']}, seed {d['seed']}: mean best val MF1 {100 * d['mean_arm']:.2f} vs "
                 f"{100 * d['mean_ref']:.2f} ({d['diff_points']:+.2f} points, tolerance {d['tol_points']:.1f}): **{d['status']}**")
# minutes per run per arm and peak memory, from train_summary.json of the runs trained in this session
import statistics
per_arm = {}
for l in log:
    m = re.search(r"train (\S+): ok", l)
    if m:
        s_ = json.loads(Path(f"runs/{m.group(1)}/train_summary.json").read_text())
        arm = json.loads(json.dumps(__import__("yaml").safe_load(Path(f"runs/{m.group(1)}/config.yaml").read_text())))["arm"]
        per_arm.setdefault(arm, []).append((s_["wall_sec"] / 60, s_.get("gpu_peak_mb")))
L += ["", "## Minutes per run per arm (training wall time from train_summary.json)", "",
      "| arm | runs | median min | max min | peak GPU MB |", "| --- | ---: | ---: | ---: | ---: |"]
for arm, v in per_arm.items():
    L.append(f"| {arm} | {len(v)} | {statistics.median(x for x, _ in v):.1f} | {max(x for x, _ in v):.1f} | "
             f"{max((p for _, p in v if p), default='')} |")
seed_sets = a.seeds.split(";") if a.seeds else [None]
for ss in seed_sets:
    out = f"reports/e1_interim_s{ss.replace(',', '')}" if ss else "reports/e1"
    cmd = [sys.executable, "scripts/aggregate.py", "e1", "--out", out] + (["--seeds", ss] if ss else [])
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)
    body = Path(f"{out}.md").read_text().split("\n", 1)[1]
    L += ["", f"## Results ({'INTERIM, seeds ' + ss if ss else 'all seeds run so far'}; from {out}.md)", "",
          body.replace("\n## ", "\n### ")]
for ss in seed_sets:      # H1 primary statistic (EXPERIMENT_PLAN section 7, D-024), INTERIM per seed set
    cmd = [sys.executable, "scripts/aggregate.py", "h1"] + (["--seeds", ss] if ss else [])
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode == 0:
        body = Path(f"{r.stdout.strip().splitlines()[-1]}.md").read_text()
        L += ["", body.replace("\n## ", "\n### ").replace("# H1", "## H1", 1)]
units, _ = parse_plan(a.plan)
from session_queue import est_train, load_times  # noqa: E402
times = load_times()
nxt = [u for u in units if u["kind"] == "train" and not unit_done(u)]
L += ["## Next (open units of the priority list, at the measured speed)", ""]
tot = 0.0
for u in nxt:
    need = sum(est_train(i, times) for i in u["items"])
    if tot + 1.3 * need > 11.75 * 3600:
        break
    tot += 1.3 * need
    L.append(f"- {' + '.join(i['name'] for i in u['items'])} (about {need / 60:.0f} min)")
L.append(f"\nThese fit one 12-hour session under the 1.3x rule: about {tot / 3600:.1f} h with the margin "
         "(estimates are the largest measured time per arm; unmeasured arms use a conservative prior).")
Path(f"reports/session_{a.n}.md").write_text("\n".join(L) + "\n")
print(f"reports/session_{a.n}.md")
