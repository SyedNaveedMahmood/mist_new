#!/usr/bin/env python
"""Writes experiments/priority.txt, the session priority list of EXPERIMENT_PLAN section 12 (owner, 2026-11-23).

Pairs are interleaved by fold (cascade2 fold f, then cascade2_placebo fold f) and joined with '&train' so a
pair starts only when both runs fit. The validation-gate fallback (band_width 32) is written as a second
branch with the same order; if the fallback also fails, the cascade2 queue stops and the GPU runs the
parallel block (P9) instead.
"""
from pathlib import Path

FOLDS = range(5)


def cv(name, arm, *ov):
    return f"train {name} {arm} cv " + " ".join(ov)


def pair(a, b, seed, prefix="e1", extra=()):
    out = []
    for f in FOLDS:
        ov = (f"split.fold={f}", f"train.seed={seed}", *extra)
        out.append(cv(f"{prefix}_{a}_cv{f}_s{seed}", a, *ov))
        out.append("&" + cv(f"{prefix}_{b}_cv{f}_s{seed}", b, *ov))
    return out


def single(a, seeds, prefix="e1", tag="", extra=()):
    return [cv(f"{prefix}_{a}{tag}_cv{f}_s{s}", a, f"split.fold={f}", f"train.seed={s}", *extra)
            for s in seeds for f in FOLDS]


def age(c, p):
    out = []
    for s in range(3):
        for d in ("young2old", "old2young"):
            ov = f"split.protocol={d} split.fold=0 train.seed={s}"
            out.append(f"train e1_raw_{d}_s{s} raw age {ov}")
            out.append(f"train e1_{c}_{d}_s{s} {c} age {ov}")
            out.append(f"&train e1_{p}_{d}_s{s} {p} age {ov}")
    return out


def e3(c, p):
    out = []
    for s in range(3):
        for f in FOLDS:
            for arm in (c, p):
                r = f"runs/e1_{arm}_cv{f}_s{s}"
                out += [f"eval {r} --cells e3", f"eval {r} --cells e3 --channel Pz-Oz",
                        f"eval {r} --cells e3 --protocol sc2st"]
    return out


def parallel():
    out = []
    for f in FOLDS:
        for arm in ("grm", "gr", "grm_placebo"):
            out.append(cv(f"e1_{arm}_cv{f}_s0", arm, f"split.fold={f}", "train.seed=0"))
    return out


def rest(c, p, a):
    """P2 onwards for cascade arm c, its placebo p and its absolute variant a."""
    L = ["# P2 seed 1"] + pair(c, p, 1)
    L += ["# P3 seed 2 (H1 confirmatory on 3 seeds)"] + pair(c, p, 2)
    L += ["# P4 absolute variant, seed 0 (H3)"] + single(a, [0])
    L += ["# P5 age shift, both directions, 3 seeds"] + age(c, p)
    L += ["# P6 E3, evaluation only, on the P1-P3 checkpoints"] + e3(c, p)
    L += ["# P7 E2 trimmed: destroy_prob 0.5; critic_weight 0 and 1.0 (seed 0)"]
    L += single(c, [0], "e2", "_dp0.5", ("model.destroy_prob=0.5",))
    L += single(c, [0], "e2", "_cw0", ("model.critic_weight=0.0",))
    L += single(c, [0], "e2", "_cw1", ("model.critic_weight=1.0",))
    L += ["# P8 E4: placebo with three N1 weights (seed 0)"]
    for w in ("1.5", "2.0", "3.0"):
        L += single(p, [0], "e4", f"_n1w{w}", (f"train.n1_weight={w}",))
    L += ["# P9 parallel model, seed 0 (e1_grm_cv0_s0 exists)"] + parallel()
    L += ["# P10 E4 without sequence context (seed 0)"] + pair(c, p, 0, "e4ctx0", ("model.context_layers=0",))
    L += ["# P11 absolute variant seeds 1 and 2, then the N-target arm"] + single(a, [1, 2])
    L += single(c, [0], "e4", "_ntarget", ("model.critic_stages=[0,1,4]",))
    return L


L = ["# Generated by scripts/make_priority.py; do not edit by hand. EXPERIMENT_PLAN section 12.",
     "# Pending evaluations from before revision 3 (pending phase only)",
     "pending runs/e1_cascade_cv4_s0 --cells core --protocol sc2st",
     "pending runs/e1_grm_cv0_s0 --cells core", "pending runs/e1_grm_cv0_s0 --cells core --channel Pz-Oz",
     "pending runs/e1_grm_cv0_s0 --cells core --protocol sc2st",
     "# P1 cascade2 and placebo, seed 0; the first cascade2 run is the timing run",
     *pair("cascade2", "cascade2_placebo", 0),
     "# validation gate (validation only): within 1.0 point of the full-rate cascade, seed 0",
     "check gate_fail .venv/bin/python scripts/gate_cascade2.py --arm cascade2",
     *rest("cascade2", "cascade2_placebo", "cascade2_absolute"),
     "stop",
     "label gate_fail",
     "# fallback: band_width 32, rerun the 5 folds and check again",
     *single("cascade2w32", [0]),
     "check gate_fail2 .venv/bin/python scripts/gate_cascade2.py --arm cascade2w32",
     "# fallback passed: placebo with the same width, then the same order",
     *pair("cascade2w32", "cascade2w32_placebo", 0),        # cascade2w32 runs are done; only the placebo trains
     *rest("cascade2w32", "cascade2w32_placebo", "cascade2w32_absolute"),
     "stop",
     "label gate_fail2",
     "# fallback failed: all cascade2 work stops (report to owner); GPU runs P9, then the raw runs of P5 (owner, 2026-11-24)",
     *parallel(),
     *[l for l in age("cascade2", "cascade2_placebo") if " raw " in l],
     "stop"]
Path("experiments/priority.txt").write_text("\n".join(L) + "\n")
print(len(L), "lines")
